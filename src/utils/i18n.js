export const getLang = () => {
  if (typeof window === "undefined") return "AZ";
  return window.localStorage.getItem("perde_lang") || "AZ";
};

export const setLang = (lang) => {
  if (typeof window === "undefined") return;
  window.localStorage.setItem("perde_lang", lang);
  window.dispatchEvent(new CustomEvent("perde:language", { detail: lang }));
};

