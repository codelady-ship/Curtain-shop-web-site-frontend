const snakeCaseKey = (value = "") => String(value).replace(/([A-Z])/g, "_$1").toLowerCase();

export const localized = (item, base, lang = getLang(), fallback = "") => {
  if (!item) return fallback;

  const normalizedLang = String(lang || "AZ").toUpperCase();
  const suffix = normalizedLang.charAt(0) + normalizedLang.slice(1).toLowerCase();
  const langLower = normalizedLang.toLowerCase();
  const snakeBase = snakeCaseKey(base);

  const candidates = [
    `${base}${suffix}`,
    `${base}_${langLower}`,
    `${snakeBase}_${langLower}`,
    `${base}${normalizedLang}`,
    `${base}_${normalizedLang}`,
    `${base}Az`,
    `${base}_az`,
    `${snakeBase}_az`,
  ];

  if (base === "description") {
    candidates.push(
      `detail${suffix}`,
      `detail_${langLower}`,
      `details${suffix}`,
      `details_${langLower}`,
      `productInfo${suffix}`,
      `product_info_${langLower}`,
      "detail",
      "details",
      "productInfo",
      "product_info",
      "desc",
    );
  }

  for (const key of candidates) {
    const value = item?.[key];
    if (value !== undefined && value !== null && String(value).trim() !== "") return value;
  }

  return item?.[base] || fallback;
};
